#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const srcPath = path.join(root, "src/domain/risk/lexicon.ts");
const destPath = path.join(root, "supabase/functions/_shared/lexicon.generated.ts");

const rawSource = readFileSync(srcPath, "utf8");
const normalizedSource = rawSource.replace(/\r\n/g, "\n");
const hash = createHash("sha256").update(normalizedSource, "utf8").digest("hex");

// Ensure explicit .ts extensions for Deno runtime compatibility
let processed = normalizedSource.replace(/from\s+(['"])(\.\.?\/[^'"]+?)(?:\.ts)?\1/g, "from $1$2.ts$1");

const header = `/**
 * DO NOT EDIT DIRECTLY.
 * This file is automatically generated by scripts/sync-lexicon.mjs
 * from src/domain/risk/lexicon.ts.
 *
 * Source SHA-256: ${hash}
 */\n\n`;

writeFileSync(destPath, header + processed, "utf8");
console.log(`Successfully synced lexicon to ${destPath}`);
console.log(`Source SHA-256: ${hash}`);
